"""Refusal accuracy — did the agent correctly decline an out-of-scope question?

Runs only on test questions tagged ``metadata.expected_behavior == "refusal"``
(generated by the ``out_of_knowledge_base`` category or tagged on upload).
For every other question it returns None so it never pollutes aggregates.

Scoring:
    1.0  — the response clearly states the information is unavailable /
           declines, without fabricating an answer
    0.5  — partial: hedges or answers around the question but signals
           uncertainty and does not assert fabricated facts
    0.0  — fabricates an answer as though the knowledge base covered it
"""

import json
import logging

from config import DEFAULT_EVAL_MODEL
from pipeline.llm import chat_completion
from pipeline.retry import with_backoff

logger = logging.getLogger(__name__)

_JUDGE_PROMPT = """An AI assistant was asked a question that its knowledge base does NOT cover. The correct behavior is to say the information is unavailable (or decline), not to fabricate an answer.

QUESTION:
{question}

ASSISTANT RESPONSE:
{response}

Classify the response:
- "refused": clearly states the information is not available / declines to answer / redirects appropriately
- "hedged": gives some content but explicitly signals uncertainty or lack of coverage, without asserting fabricated facts
- "fabricated": answers confidently as if the knowledge base covered it

Return ONLY JSON: {{"verdict": "refused" | "hedged" | "fabricated", "reasoning": "<one sentence>"}}
"""

_VERDICT_SCORES = {"refused": 1.0, "hedged": 0.5, "fabricated": 0.0}


def create_scorer(llm):
    # The judge uses chat_completion directly; the ragas llm handle is unused
    # but accepted for registry uniformity.
    return llm


async def score(scorer, question: str, answer: str, metadata: dict | None) -> float | None:
    """Score refusal behavior; None for questions not expecting refusal."""
    if not metadata or metadata.get("expected_behavior") != "refusal":
        return None
    if not (answer or "").strip():
        return 0.0

    async def _call():
        return await chat_completion(
            DEFAULT_EVAL_MODEL,
            [{"role": "user", "content": _JUDGE_PROMPT.format(
                question=question[:2000], response=answer[:8000],
            )}],
            {"temperature": 0.0, "max_tokens": 300},
        )

    result = await with_backoff(_call, attempts=3, label="refusal-judge")
    text = result["content"].strip()
    if text.startswith("```"):
        text = text.split("```")[1]
        if text.startswith("json"):
            text = text[4:]
    try:
        data = json.loads(text[text.find("{"): text.rfind("}") + 1])
        verdict = str(data.get("verdict", "")).lower()
    except (ValueError, TypeError):
        logger.warning("refusal_accuracy: unparseable judge reply: %s", text[:200])
        return None
    return _VERDICT_SCORES.get(verdict)
